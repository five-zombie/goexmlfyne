package main

import (
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func writeFile(t *testing.T, dir, name, content string) string {
	t.Helper()
	p := filepath.Join(dir, name)
	if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
	return p
}

func generate(t *testing.T, inputs []string, out string) string {
	t.Helper()
	if err := run(inputs, out, "gen"); err != nil {
		t.Fatalf("run: %v", err)
	}
	src, err := os.ReadFile(filepath.Join(out, "goexmlgen.go"))
	if err != nil {
		t.Fatal(err)
	}
	return string(src)
}

const docA = `<goexml-item version="0.1.0">` +
	`<vbox id="b"><label id="a1" text="hi"/></vbox></goexml-item>`

// The bundle parses as Go, carries the header, names functions after
// their files, and is byte-for-byte deterministic.
func TestGenerateParsesAndDeterministic(t *testing.T) {
	dir := t.TempDir()
	inA := writeFile(t, dir, "page-body.xml", docA)
	out := filepath.Join(dir, "gen")
	src := generate(t, []string{inA}, out)

	if !strings.Contains(src, "Code generated by goexmlgen; DO NOT EDIT.") {
		t.Fatalf("missing generated header:\n%s", src)
	}
	if _, err := parser.ParseFile(token.NewFileSet(), "goexmlgen.go", src, 0); err != nil {
		t.Fatalf("generated code does not parse: %v\n%s", err, src)
	}
	if !strings.Contains(src, "func PageBody() *goexml.Node") {
		t.Fatalf("missing deterministic function name:\n%s", src)
	}
	if !strings.Contains(src, "(fragment)") {
		t.Fatalf("goexml-item input not marked as fragment:\n%s", src)
	}
	if src2 := generate(t, []string{inA}, out); src != src2 {
		t.Fatal("two runs produced different output")
	}
}

// A directory input contributes its sorted .xml files.
func TestGenerateDirectoryInput(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, dir, "b.xml", docA)
	writeFile(t, dir, "a.xml", `<goexml version="0.1.0"><window title="y"><label id="a2" text="y"/></window></goexml>`)
	src := generate(t, []string{dir}, filepath.Join(dir, "gen"))
	if !strings.Contains(src, "func A() *goexml.Node") || !strings.Contains(src, "func B() *goexml.Node") {
		t.Fatalf("directory files not both generated:\n%s", src)
	}
}

// Broken XML fails the generation with file and line.
func TestGenerateBrokenXML(t *testing.T) {
	dir := t.TempDir()
	in := writeFile(t, dir, "broken.xml",
		"<goexml version=\"0.1.0\">\n  <window title=\"x\" size=\"1x1\">\n    <label id=\"a\" text=\"x\">\n  </window>\n</goexml>")
	err := run([]string{in}, filepath.Join(dir, "gen"), "gen")
	if err == nil {
		t.Fatal("broken XML generated successfully")
	}
	if !strings.Contains(err.Error(), "broken.xml") || !strings.Contains(err.Error(), "line 4") {
		t.Fatalf("error %q does not carry file and line", err)
	}
}

// Duplicate ids across input files fail the generation.
func TestGenerateDuplicateID(t *testing.T) {
	dir := t.TempDir()
	inA := writeFile(t, dir, "a.xml", docA)
	inB := writeFile(t, dir, "b.xml",
		`<goexml version="0.1.0"><window title="y"><label id="b1" text="y"/></window></goexml>`)
	// Same id a1 in both files, different files: rejected.
	inB2 := writeFile(t, dir, "c.xml",
		`<goexml version="0.1.0"><window title="z"><label id="a1" text="z"/></window></goexml>`)
	err := run([]string{inA, inB2}, filepath.Join(dir, "gen"), "gen")
	if err == nil || !strings.Contains(err.Error(), `id "a1" is already used by`) {
		t.Fatalf("duplicate id across files: err = %v", err)
	}
	// Distinct ids across files: fine, and ids repeated inside one
	// file are the parser's problem (already rejected by Decode).
	if err := run([]string{inA, inB}, filepath.Join(dir, "gen"), "gen"); err != nil {
		t.Fatalf("distinct ids rejected: %v", err)
	}
}

// Files mapping to the same function name are rejected.
func TestGenerateNameCollision(t *testing.T) {
	dir := t.TempDir()
	inA := writeFile(t, dir, "page-body.xml", docA)
	inB := writeFile(t, dir, "page_body.xml",
		`<goexml version="0.1.0"><window title="y"><label id="b1" text="y"/></window></goexml>`)
	err := run([]string{inA, inB}, filepath.Join(dir, "gen"), "gen")
	if err == nil || !strings.Contains(err.Error(), "already used by another input file") {
		t.Fatalf("name collision: err = %v", err)
	}
}

// Non-XML inputs are rejected instead of silently skipped.
func TestGenerateNonXMLInput(t *testing.T) {
	dir := t.TempDir()
	in := writeFile(t, dir, "notes.txt", "hello")
	if err := run([]string{in}, filepath.Join(dir, "gen"), "gen"); err == nil {
		t.Fatal("non-xml input accepted")
	}
}

// File names that do not map to a valid Go identifier are rejected by
// name, not by a confusing Go parser error after generation.
func TestGenerateInvalidIdentifierNames(t *testing.T) {
	for _, name := range []string{"01-intro.xml", "123.xml", "1page.xml", ".xml"} {
		dir := t.TempDir()
		in := writeFile(t, dir, name, docA)
		err := run([]string{in}, filepath.Join(dir, "gen"), "gen")
		if err == nil {
			t.Fatalf("%s: accepted as if it were a valid function name", name)
		}
		if !strings.Contains(err.Error(), name) ||
			!strings.Contains(err.Error(), "is not a valid Go identifier") {
			t.Fatalf("%s: error %q does not name the file and the identifier problem", name, err)
		}
		// Nothing was written: the rejection happens before output.
		if _, statErr := os.Stat(filepath.Join(dir, "gen", "goexmlgen.go")); !os.IsNotExist(statErr) {
			t.Fatalf("%s: generated output written despite the rejection", name)
		}
	}
}
